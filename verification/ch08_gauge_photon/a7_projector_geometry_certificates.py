def rank_mod_p(Mx, pr_=PRIME):
    Mx = np.array(Mx, dtype=object) % pr_
    Mx = np.array(Mx, dtype=np.int64)
    rows, cols = Mx.shape
    r = 0
    for c in range(cols):
        nz = np.nonzero(Mx[r:, c])[0]
        if nz.size == 0:
            continue
        piv = r + nz[0]
        Mx[[r, piv]] = Mx[[piv, r]]
        inv = pow(int(Mx[r, c]), pr_ - 2, pr_)
        Mx[r] = (Mx[r] * inv) % pr_
        others = np.nonzero(Mx[:, c])[0]
