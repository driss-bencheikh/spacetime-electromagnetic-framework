#!/usr/bin/env python3
"""Generate the theorem-to-code table of Appendix D (Phase 9F, 2 November 2026).

    python3 verification/make_appendix_d.py

Inputs: verification/MANIFEST.tsv (every check, its script, method and the manuscript labels whose statement cites it),
verification/COVERAGE.tsv (every labelled statement of the manuscript with its provenance and whether a written proof is present),
the audit checks (verification/chNN_*/a[1-8]_*.py: Phase 9D and the v1.0.0 release audit; their claim text names the labels they
test), and
reproducibility/selected-results/uncited_related_checks.tsv (checks that test a statement without being cited by it).
Outputs: manuscript/chapters/appendix_d_table.tex (a longtable: label, chapter, kind, evidence, method), verification/THEOREM_CODE.tsv
(the same table in machine-readable form) and a printed coverage summary.

The table records evidence, not proof: a check listed against a label tests the coded assertion stated in its claim text.
"""
import csv
import pathlib
import re
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parents[2]
csv.field_size_limit(10 ** 7)


def read_tsv(p):
    with open(p, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


manifest = read_tsv(ROOT / "verification" / "MANIFEST.tsv")
coverage = read_tsv(ROOT / "verification" / "COVERAGE.tsv")
related = read_tsv(ROOT / "reproducibility" / "selected-results" / "uncited_related_checks.tsv")
labels = [r for r in coverage if r["label"] and not r["label"].startswith("(")]
known = {r["label"] for r in labels}

method = {r["check"]: r["method"] for r in manifest}
script = {r["check"]: r["script"] for r in manifest}
status = {r["check"]: r["status"] for r in manifest}
ev = defaultdict(lambda: {"cited": set(), "audit": set(), "related": set()})
for r in manifest:
    for lab in filter(None, r["manuscript_labels"].split(";")):
        ev[lab]["cited"].add(r["check"])
    if r["check"].startswith("a") and re.match(r"a\d-", r["check"]):
        head = r["claim"]
        for lab in known:
            if re.search(r"(?<![\w:])" + re.escape(lab) + r"(?!\w|:\w)", head):
                ev[lab]["audit"].add(r["check"])
for r in related:
    ids = (r.get("checks naming the label", "") + " " + r.get("checks citing its 26 October theorem number", "")).split()
    for c in ids:
        if c in method:
            ev[r["label"]]["related"].add(c)

rows = []
for r in labels:
    lab = r["label"]
    e = ev.get(lab, {"cited": set(), "audit": set(), "related": set()})
    checks = sorted(e["cited"] | e["audit"] | e["related"])
    meth = sorted({method[c] for c in checks})
    if checks:
        kind = "exact" if meth == ["exact"] else ("numerical" if meth == ["numerical"] else "exact+numerical")
    elif r["written_proof"] == "yes":
        kind = "proof in text"
    elif r["cites_literature"] == "yes" or "inherited" in r["markers"]:
        kind = "inherited"
    elif "conjecture" in r["markers"] or r["environment"] == "conjecture":
        kind = "conjecture"
    else:
        kind = "argument in text"
    rows.append({"label": lab, "chapter": r["file"], "environment": r["environment"], "written_proof": r["written_proof"],
                 "cited_checks": " ".join(sorted(e["cited"])), "audit_checks": " ".join(sorted(e["audit"])),
                 "related_checks": " ".join(sorted(e["related"])), "evidence": kind,
                 "scripts": " ".join(sorted({script[c].rsplit("/", 1)[-1] for c in checks}))})

with open(ROOT / "verification" / "THEOREM_CODE.tsv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]), delimiter="\t")
    w.writeheader()
    w.writerows(rows)


def tex(s):
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def short(ids, k=6):
    ids = ids.split()
    return " ".join(ids[:k]) + (f" (+{len(ids) - k})" if len(ids) > k else "")


chap_title = {}
lines = [r"% GENERATED by verification/tools/make_appendix_d.py from MANIFEST.tsv, COVERAGE.tsv and the audit checks; do not edit.",
         r"{\scriptsize", r"\setlength{\tabcolsep}{3pt}",
         r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{3.3cm}>{\raggedright\arraybackslash}p{1.6cm}>{\raggedright\arraybackslash}p{6.2cm}>{\raggedright\arraybackslash}p{2.3cm}@{}}",
         r"\caption{Theorem-to-code table: every labelled statement, its evidence and the checks that test it (cited in the text, added by the"
         r" Phase-9 audit, or testing it without citation). Scripts are listed in \cref{tab:scripts}.}\label{tab:theoremcode}\\",
         r"\toprule statement & kind & checks & evidence\\ \midrule \endfirsthead",
         r"\toprule statement & kind & checks & evidence\\ \midrule \endhead"]
cur = None
for r in rows:
    if r["chapter"] != cur:
        cur = r["chapter"]
        lines.append(r"\multicolumn{4}{@{}l}{\textbf{" + tex(cur) + r"}}\\")
    ids = " ".join(x for x in (r["cited_checks"], r["audit_checks"], r["related_checks"]) if x)
    lines.append(r"\texttt{" + tex(r["label"]) + "} & " + r["environment"] + " & " + tex(short(ids)) + " & " + r["evidence"] + r"\\")
lines += [r"\bottomrule", r"\end{longtable}}"]
(ROOT / "manuscript" / "chapters" / "appendix_d_table.tex").write_text("\n".join(lines) + "\n")

# scripts table
by_script = defaultdict(lambda: [0, 0])
for r in manifest:
    by_script[r["script"]][0 if r["method"] == "exact" else 1] += 1
sl = [r"% GENERATED by verification/tools/make_appendix_d.py; do not edit.", r"{\scriptsize",
      r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{9.5cm}rr@{}}",
      r"\caption{The verification scripts, by directory, with their numbers of exact and numerical checks (all \texttt{PASS} in the version 1.0.0"
      r" regression of \texttt{reproducibility/selected-results/v1.0.0}).}\label{tab:scripts}\\",
      r"\toprule script & exact & numerical\\ \midrule \endfirsthead \toprule script & exact & numerical\\ \midrule \endhead"]
for s_, (a, b) in sorted(by_script.items()):
    sl.append(r"\path{" + s_ + "} & " + str(a) + " & " + str(b) + r"\\")
sl += [r"\midrule total & " + str(sum(v[0] for v in by_script.values())) + " & " + str(sum(v[1] for v in by_script.values())) + r"\\",
       r"\bottomrule", r"\end{longtable}}"]
(ROOT / "manuscript" / "chapters" / "appendix_d_scripts.tex").write_text("\n".join(sl) + "\n")

n = len(rows)
cnt = defaultdict(int)
for r in rows:
    cnt[r["evidence"]] += 1
with_check = sum(1 for r in rows if r["cited_checks"] or r["audit_checks"] or r["related_checks"])
print(f"{n} labelled statements; with a check: {with_check}; by evidence: {dict(cnt)}")
print(f"checks: {len(manifest)} ({sum(1 for r in manifest if r['status'] == 'PASS')} PASS); scripts: {len(by_script)}")
