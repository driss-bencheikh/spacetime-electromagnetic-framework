#!/usr/bin/env python3
"""Write the reproducibility indexes from verification/MANIFEST.tsv and verification/THEOREM_CODE.tsv.

    python3 verification/tools/make_reproducibility_index.py

Outputs: reproducibility/manifest.json (one record per check: identifier, statement labels, script, command, method, expected and
observed output, run record, dependencies, limitation), reproducibility/selected-results/EXACT_CHECKS.tsv and
reproducibility/selected-results/NUMERICAL_CHECKS.tsv (the exact and the numerical checks with their claim texts).
"""
import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
csv.field_size_limit(10 ** 7)
man = list(csv.DictReader(open(ROOT / "verification" / "MANIFEST.tsv", newline=""), delimiter="\t"))
tc = list(csv.DictReader(open(ROOT / "verification" / "THEOREM_CODE.tsv", newline=""), delimiter="\t"))
by_check = {}
for r in tc:
    for c in (r["cited_checks"] + " " + r["audit_checks"] + " " + r["related_checks"]).split():
        by_check.setdefault(c, []).append(r["label"])
COMMON = {"common/clifford8.py", "ch07_mass_vacuum/kernel_space.py", "ch07_mass_vacuum/tensor_model.py", "ch11_curvature_gravity/curvature.py"}


def deps(script):
    text = (ROOT / script).read_text()
    d = [m for m in ("numpy", "scipy", "sympy", "mpmath") if f"import {m}" in text or f"from {m}" in text]
    d += sorted(f"verification/{c}" for c in COMMON if pathlib.Path(c).stem in text and f"import" in text and f"verification/{c}" != script)
    return d


records = []
dep_cache = {}
for r in man:
    s = r["script"]
    dep_cache.setdefault(s, deps(s))
    labels = sorted(set(filter(None, r["manuscript_labels"].split(";"))) | set(by_check.get(r["check"], [])))
    lim = ("floating-point check: holds within the stated tolerance at the sampled inputs" if r["method"] == "numerical"
           else "exact check of the coded assertion; it verifies the statement only to the extent that the assertion is the statement")
    rec = {"id": r["check"], "labels": labels, "script": s, "command": r["command"], "method": r["method"],
           "expected": "PASS: " + r["claim"], "observed": r["status"], "run_record": r["run_record"], "dependencies": dep_cache[s],
           "limitation": lim}
    records.append(rec)
doc = {"description": "Executable checks of the manuscript; generated by verification/tools/make_reproducibility_index.py from "
                      "verification/MANIFEST.tsv. expected: the asserted claim (the script prints PASS for it); observed: the status "
                      "in the run record.",
       "version": "1.0.0", "checks_total": len(records),
       "checks_exact": sum(r["method"] == "exact" for r in records),
       "checks_numerical": sum(r["method"] == "numerical" for r in records),
       "checks": records}
(ROOT / "reproducibility" / "manifest.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")
for kind in ("exact", "numerical"):
    out = ROOT / "reproducibility" / "selected-results"
    out.mkdir(parents=True, exist_ok=True)
    rows = [r for r in man if r["method"] == kind]
    with open(out / ("EXACT_CHECKS.tsv" if kind == "exact" else "NUMERICAL_CHECKS.tsv"), "w", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(["check", "status", "script", "labels", "run_record", "claim"])
        for r in rows:
            w.writerow([r["check"], r["status"], r["script"], ";".join(sorted(set(filter(None, r["manuscript_labels"].split(";"))) |
                        set(by_check.get(r["check"], [])))), r["run_record"], r["claim"]])
print(f"manifest.json: {len(man)} checks; exact {sum(r['method'] == 'exact' for r in man)}, numerical {sum(r['method'] == 'numerical' for r in man)}")
